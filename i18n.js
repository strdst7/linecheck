let current = "en";
export const setLang = (code) => { current = STRINGS[code] ? code : "en"; };
export const getLang = () => current;
// Missing key falls back to English, then to the key, so a gap is visible but never blank.
export const t = (key, vars) => {
  let s = STRINGS[current][key] ?? STRINGS.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
  return s;
};
